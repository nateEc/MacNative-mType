#!/usr/bin/env python3
"""Prepare independent five-letter English pools; never reads reference words."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import unittest

PARENT_SHA = "94b7036c27bbff858fee1731a7925192aa39d3e6f96772ee16259cf66990523b"
RAW_SHA = "c8f999c724e322801d94348a90f940e28f8bbbd19e53a4ffed18346d83ae52ad"
REVISION = "scowl95-wordfreq-3.1.1-five-letter-v1"
LEGACY = "amber quiet paper drift cabin cedar flint glass grain shore trail bloom crane field light ocean river stone cloud maple wheat slope spark frame brush clock prism sound green dream swift focus learn write clear paths hands lines shape steps".split()
SWIFT = Path("Sources/Typebar/EnglishFiveLetterCorpus.generated.swift")
NOTICE = Path("Resources/EnglishFiveLetterCorpusNotices.txt")
ROWS = Path("Resources/EnglishFiveLetterCorpusSources.txt")
MANIFEST = Path("Compatibility/english-five-letter-corpus.json")
PUBLISHED = {
    str(SWIFT): "11e0bd3a7215fbadd22801cb4063a3ed062ac2467d92be5b9bdcf532801dbce9",
    str(NOTICE): "2f7247673678da0787cbb446ace1f76ecbb594e558d5ef162664414d4b500067",
    str(ROWS): "323c697094922c25a6821cda7641cf7d18a18782756b6b6d3f0e53cbd221969d",
}
MANIFEST_SHA = "647cc3879b0eb123cfca2f57a0098c4ff52482f046b9e66d5023a8d87a9959b0"


def require(value, message):
    if not value:
        raise ValueError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def parent_module(root):
    path = root / "Scripts/prepare-english-large-corpus.py"
    require(sha(path.read_bytes()) == PARENT_SHA, "shared English reader pin mismatch")
    spec = importlib.util.spec_from_file_location("five_letter_sources", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def eligible(word, bands):
    return type(word) is str and re.fullmatch(r"[a-z]{5}", word) is not None and word in bands


def select(dictionary, sizes, bands, count, required):
    candidates = sorted({w for w in dictionary if eligible(w, bands)}, key=lambda w: (bands[w], sizes[w], w))
    chosen = set(required)
    require(type(count) is int and count > 0 and len(chosen) <= count, "invalid selection size")
    require(chosen <= set(candidates), "required word lacks dictionary or whole-token observation")
    require(len(candidates) >= count, "insufficient real five-letter forms; never pad")
    for word in candidates:
        if len(chosen) == count:
            break
        chosen.add(word)
    return sorted(chosen, key=lambda w: (bands[w], sizes[w], w)), len(candidates)


def native(pools):
    text = ("// Generated by Scripts/prepare-english-five-letter-corpus.py; do not edit.\n"
            "// Independent SCOWL / wordfreq selection; full notices and UKACD attribution retained.\n"
            "enum EnglishFiveLetterCorpus {\n" + f'  static let revision = "{REVISION}"\n')
    for name, words in pools.items():
        text += f'  static let {name}: [String] = """\n' + "\n".join(words) + '\n""".split(separator: "\\n").map(String.init)\n'
    return (text + "}\n").encode()


def artifacts(parent, scowl, wheel):
    dictionary, sizes, raw, copyright_text = parent.read_dictionary(scowl)
    require(sha(raw) == RAW_SHA, "fixed SCOWL extraction mismatch")
    bins, _, wordfreq_notice = parent.read_frequency(wheel)
    bands = parent.frequency_bands(bins)
    basic, capacity = select(dictionary, sizes, bands, 201, LEGACY)
    large, _ = select(dictionary, sizes, bands, 1000, basic)
    pools = {"basic": basic, "large": large}
    notice = ("Typebar independent five-letter English corpora\nRevision: " + REVISION + "\n\n"
              "SCOWL: https://github.com/en-wl/wordlist\nCommit: " + parent.SCOWL_COMMIT + "\n"
              "Dictionary extraction: size 95, spellings A/B/Z/C, variant level 1;\n"
              "same fixed extraction and full source notices as the independent English large reader.\n"
              "SCOWL raw SHA-256: " + RAW_SHA + "\n"
              "wordfreq 3.1.1 wheel SHA-256: " + parent.WHEEL_SHA + "\n"
              "English member: " + parent.MEMBER + "\nMember SHA-256: " + parent.MEMBER_SHA + "\n\n"
              "Changes: select 201 / 1000 unique literal five-letter lowercase ASCII dictionary forms\n"
              "with whole-token wordfreq observations; retain all 40 earlier authored words,\n"
              "and include the basic selection in the 1k pool. Order by observation band,\n"
              "SCOWL minimum level, then literal spelling. A band is not a usage count.\n"
              "No case conversion, accents removed, synthetic suffixes, repeated-letter padding,\n"
              "or reference-project word values. Historical captured prompts remain literal.\n"
              "Count and alphabet matching do not establish original word values, order,\n"
              "difficulty, frequency distribution, Wordle answer eligibility or language quality.\n"
              "Adapted combined selection: CC BY-SA 4.0; retain every source notice below.\n"
              "Includes material from the UK Advanced Cryptics Dictionary.\n\n"
              + parent.SCOWL_MARKER + copyright_text.rstrip() + "\n\n"
              + parent.WORDFREQ_MARKER + wordfreq_notice.rstrip() + "\n")
    rows = "# word\tSCOWLMinimumLevel\twordfreqWholeTokenBand\n"
    rows += "".join(f"{word}\t{sizes[word]}\t{bands[word]}\n" for word in large)
    outputs = {SWIFT: native(pools), NOTICE: notice.encode(), ROWS: rows.encode()}
    document = {"schemaVersion": 1, "revision": REVISION, "sharedReaderSHA256": PARENT_SHA,
        "scowlCommit": parent.SCOWL_COMMIT, "rawSHA256": RAW_SHA, "scowlCopyrightSHA256": parent.SCOWL_COPYRIGHT_SHA,
        "frequencyWheelSHA256": parent.WHEEL_SHA, "frequencyMemberSHA256": parent.MEMBER_SHA,
        "eligibleCandidates": capacity, "retainedAuthored": LEGACY, "basicSubsetOfLarge": True,
        "wholeTokenObservationsRequired": True, "runtimeDependencies": [],
        "pools": {k: {"count": len(v), "wordsSHA256": sha(("\n".join(v) + "\n").encode())} for k, v in pools.items()},
        "filesSHA256": {str(k): sha(v) for k, v in outputs.items()}}
    outputs[MANIFEST] = (json.dumps(document, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()
    return outputs


def verify_pins(hashes):
    require(bool(PUBLISHED) and hashes == PUBLISHED, "immutable five-letter pins required")


def verify_bundled(root):
    parent_module(root)
    require(bool(MANIFEST_SHA) and sha((root / MANIFEST).read_bytes()) == MANIFEST_SHA, "five-letter manifest immutable pin mismatch")
    d = json.loads((root / MANIFEST).read_text())
    require(d["revision"] == REVISION and d["schemaVersion"] == 1, "unsupported five-letter revision")
    verify_pins(d["filesSHA256"])
    for path, digest in PUBLISHED.items():
        require(sha((root / path).read_bytes()) == digest, "five-letter file mismatch: " + path)
    text = (root / SWIFT).read_text()
    matches = re.findall(r'  static let (basic|large): \[String\] = """\n(.*?)\n"""', text, re.S)
    pools = {k: v.splitlines() for k, v in matches}
    require(len(matches) == len(pools) == 2 and list(pools) == ["basic", "large"] and native(pools) == text.encode(), "native template mismatch")
    rows = [r.split("\t") for r in (root / ROWS).read_text().splitlines() if not r.startswith("#")]
    require(len(rows) == 1000 and all(len(r) == 3 and r[1].isdigit() and r[2].isdigit() for r in rows), "invalid whole-token provenance")
    require([r[0] for r in rows] == pools["large"], "incomplete provenance")
    require(set(LEGACY) <= set(pools["basic"]) <= set(pools["large"]), "old words or basic pool lost")
    for name, count in [("basic", 201), ("large", 1000)]:
        words = pools[name]
        require(len(words) == len(set(words)) == count and all(re.fullmatch(r"[a-z]{5}", w) for w in words), "invalid five-letter shape")
        require(d["pools"][name] == {"count": count, "wordsSHA256": sha(("\n".join(words) + "\n").encode())}, "content metadata mismatch")


class Contracts(unittest.TestCase):
    def test_literal_observed_ascii_five_letters_only(self):
        bands = dict.fromkeys(["cabin", "Cabin", "cábín", "a-bcd", "abcde", "four", "longer"], 0)
        self.assertTrue(eligible("cabin", bands))
        for word in ["Cabin", "cábín", "a-bcd", "four", "longer", "absnt"]:
            self.assertFalse(eligible(word, bands))

    def test_stable_ranking_retains_required_words_and_refuses_padding(self):
        words = ["amber", "quiet", "paper"]
        sizes, bands = dict.fromkeys(words, 10), {"amber": 2, "quiet": 1, "paper": 0}
        self.assertEqual(select(words, sizes, bands, 2, ["amber"])[0], ["paper", "amber"])
        self.assertEqual(select(words, sizes, bands, 2, ["amber"]), select(reversed(words), sizes, bands, 2, ["amber"]))
        with self.assertRaises(ValueError): select(words, sizes, bands, 4, [])
        with self.assertRaises(ValueError): select(words, sizes, bands, 2, ["absnt"])

    def test_absent_or_mutable_manifest_pins_are_not_trusted(self):
        with self.assertRaises(ValueError): verify_pins({})
        with self.assertRaises(ValueError): verify_pins({str(SWIFT): "0" * 64})


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--scowl-root", type=Path); p.add_argument("--wordfreq-wheel", type=Path)
    p.add_argument("--output-root", type=Path, default=Path(__file__).resolve().parents[1])
    for flag in ["self-test", "check-bundled", "check"]: p.add_argument("--" + flag, action="store_true")
    a = p.parse_args()
    if a.self_test:
        return 0 if unittest.TextTestRunner().run(unittest.defaultTestLoader.loadTestsFromTestCase(Contracts)).wasSuccessful() else 1
    if a.check_bundled:
        verify_bundled(a.output_root); print("English five-letter bundled integrity passed"); return 0
    require(a.scowl_root and a.wordfreq_wheel, "two pinned sources required")
    outputs = artifacts(parent_module(Path(__file__).resolve().parents[1]), a.scowl_root, a.wordfreq_wheel)
    verify_pins({str(k): sha(v) for k, v in outputs.items() if k != MANIFEST})
    require(sha(outputs[MANIFEST]) == MANIFEST_SHA, "source manifest reproduction mismatch")
    if not a.check: require(not any((a.output_root / k).exists() for k in outputs), "refusing to overwrite five-letter artifacts")
    for path, data in outputs.items():
        target = a.output_root / path
        if a.check: require(target.read_bytes() == data, "source reproduction mismatch: " + str(path))
        else:
            target.parent.mkdir(parents=True, exist_ok=True); target.write_bytes(data)
    print("English five-letter source reproduction checked" if a.check else "English five-letter corpora prepared")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
