#!/usr/bin/env python3
"""Reproduce the basic Russian pool from pinned independent sources, QA only."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import unittest

PARENT_SHA = "66c968199417e0d869eabb4af7ce9458c1765f1f8f1491559de308dfacb06a6e"
REVISION = "kaikki-ru-20261029-wordfreq-3.1.1-basic-v1"
ALPHABET = frozenset("абвгдеёжзийклмнопрстуфхцчшщъыьэюя")
LEGACY = "утро окно бумага берег ветер практика внимание тихо ясно озеро улица стол свет дорога терпение минута город дождь спокойно направление звезда записка сад дыхание".split()
SWIFT = Path("Sources/Typebar/RussianBasicCorpus.generated.swift")
NOTICES = Path("Resources/RussianBasicCorpusNotices.txt")
SOURCES = Path("Resources/RussianBasicCorpusSources.txt")
MANIFEST = Path("Compatibility/russian-basic-corpus.json")
PUBLISHED = {
    str(SWIFT): "75f09a45a6718aa52be3a2606558dbfeccc87335974b49b3c83290bf9a7a5bdf",
    str(NOTICES): "b9f4d3a8ba642bbbde7d028171fef5e8654c768a018023dacb6c6d5e4c371184",
    str(SOURCES): "990fb153c05d1299da8d144b671bf2f4a05949d65032e5cc8bf3e375e048231e",
}
MANIFEST_SHA = "d05542c347270e03cf6fecd51d2fabd25265f61cd780e92b8c2c230b5fc70f1e"


def require(value, message):
    if not value:
        raise ValueError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def parent_module(root):
    path = root / "Scripts/prepare-russian-corpus.py"
    require(sha(path.read_bytes()) == PARENT_SHA, "shared source reader pin mismatch")
    spec = importlib.util.spec_from_file_location("russian_literal_reader", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def eligible(word, bands):
    return type(word) is str and 1 <= len(word) <= 12 and set(word) <= ALPHABET and word in bands


def native(words):
    return ("// Generated by Scripts/prepare-russian-basic-corpus.py; do not edit.\n"
            "// Independent Russian Wiktionary forms with wordfreq ordering; CC BY-SA 4.0.\n"
            "enum RussianBasicCorpus {\n"
            f'  static let revision = "{REVISION}"\n'
            '  static let words: [String] = """\n' + "\n".join(words)
            + '\n""".split(separator: "\\n").map(String.init)\n}\n').encode()


def artifacts(parent, dictionary, wheel):
    forms, rows = parent.read_dictionary(dictionary)
    bands, release_notices = parent.read_frequency(wheel)
    candidates = [word for word in forms if eligible(word, bands)]
    words, capacity = parent.select_group(candidates, (200, 1, 12, 1, 12), bands, 0, reserved=LEGACY)
    parent.validate(words, {"L": (200, 1, 12, 1, 12)})
    require(set(LEGACY) <= set(words), "existing authored candidates were lost")
    mapping = "# Literal form\tRussian Wiktionary source page title\twordfreq whole-form band\n"
    mapping += "# Pages: https://ru.wiktionary.org/wiki/<URL-encoded title>\n"
    mapping += "# Contributors: https://ru.wiktionary.org/w/index.php?title=<URL-encoded title>&action=history\n"
    mapping += "".join(word + "\t" + forms[word] + "\t" + str(bands[word]) + "\n" for word in words)
    notice = ("Typebar independent basic Russian corpus — revision 1\n"
              "Russian Wiktionary (Викисловарь) contributors; Kaikki.org / Wiktextract.\n"
              "Selection and ordering adapted by Typebar contributors (2026), CC BY-SA 4.0.\n"
              "https://creativecommons.org/licenses/by-sa/4.0/\n"
              "https://ru.wiktionary.org/\nhttps://kaikki.org/ruwiktionary/\n"
              "https://foundation.wikimedia.org/wiki/Policy:Terms_of_Use#7._Licensing_of_Content\n\n"
              "Pinned Russian-edition raw snapshot, retrieved 2026-10-29:\n" + parent.SOURCE_URL
              + "\nSHA-256: " + parent.SOURCE_SHA + "\n\n"
              "Changes: select 200 distinct literal NFC forms using modern lowercase Russian\n"
              "letters, lengths 1–12, with whole-form observations in pinned wordfreq 3.1.1.\n"
              "Preserve all 24 earlier Typebar-authored candidates when source-attested;\n"
              "preserve actual minimum/maximum lengths. Rank by wordfreq whole-form band\n"
              "then spelling. Band indexes are not observed token counts. No reference word\n"
              "values, new compounds, recasing, accent stripping, normalization rewriting\n"
              "or padding. Count and input boundaries do not prove lexical, frequency,\n"
              "difficulty or semantic equivalence. The six larger Russian pools retain\n"
              "their separate revision-1 notice and data. Historical prompt/replay text is\n"
              "not regenerated. Definitions, quotations, audio and raw source not bundled.\n\n"
              "Tatu Ylonen, Wiktextract: Wiktionary as Machine-Readable Structured Data,\n"
              "LREC 2022, pp. 1317–1325. https://aclanthology.org/2022.lrec-1.140/\n\n"
              "=== wordfreq 3.1.1 release metadata ===\n" + release_notices)
    outputs = {SWIFT: native(words), NOTICES: notice.encode(), SOURCES: mapping.encode()}
    manifest = {"schemaVersion": 1, "revision": REVISION, "sharedReaderSHA256": PARENT_SHA,
        "dictionary": {"url": parent.SOURCE_URL, "sha256": parent.SOURCE_SHA,
            "rows": rows, "eligibleForms": len(forms), "languageCode": "ru", "edition": "ru"},
        "frequency": {"wheelSHA256": parent.WHEEL_SHA, "member": parent.MEMBER,
            "memberSHA256": parent.MEMBER_SHA},
        "selection": {"wholeFormFrequencyRequired": True, "eligibleCandidates": capacity,
            "retainedAuthoredCount": len(LEGACY), "shape": parent.shape(words)},
        "referenceAggregate": {"count": 200, "minimumLength": 1, "maximumLength": 12,
            "uppercase": 0, "punctuation": 0, "spaces": 0},
        "wordsSHA256": sha(("\n".join(words) + "\n").encode()),
        "runtimeDependencies": [], "filesSHA256": {str(p): sha(v) for p, v in outputs.items()}}
    outputs[MANIFEST] = (json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode()
    return outputs


def verify_pins(hashes):
    require(bool(PUBLISHED) and hashes == PUBLISHED, "published immutable pins required")


def verify_bundled(root):
    parent = parent_module(root)
    require(sha((root / MANIFEST).read_bytes()) == MANIFEST_SHA, "basic manifest immutable pin mismatch")
    document = json.loads((root / MANIFEST).read_text())
    require(document["schemaVersion"] == 1 and document["revision"] == REVISION, "unsupported basic manifest")
    verify_pins(document["filesSHA256"])
    for path, expected in PUBLISHED.items():
        require(sha((root / path).read_bytes()) == expected, "bundled file mismatch: " + path)
    text = (root / SWIFT).read_text()
    body = re.fullmatch(r'.*?static let words: \[String\] = """\n(.*?)\n""".*', text, re.S)
    require(body is not None, "native basic literal array missing")
    words = body[1].splitlines()
    require(native(words) == text.encode(), "native basic template mismatch")
    parent.validate(words, {"L": (200, 1, 12, 1, 12)})
    require(all(set(w) <= ALPHABET for w in words) and set(LEGACY) <= set(words), "invalid basic candidates")
    rows = [line.split("\t") for line in (root / SOURCES).read_text().splitlines() if not line.startswith("#")]
    require(len(rows) == 200 and [r[0] for r in rows] == words
            and all(len(r) == 3 and r[1] and r[2].isdigit() for r in rows), "incomplete basic source mapping")
    require(document["selection"]["shape"] == parent.shape(words)
            and document["wordsSHA256"] == sha(("\n".join(words) + "\n").encode()), "basic shape/hash mismatch")
    require(document["dictionary"]["sha256"] == parent.SOURCE_SHA
            and document["frequency"]["wheelSHA256"] == parent.WHEEL_SHA
            and document["frequency"]["memberSHA256"] == parent.MEMBER_SHA
            and document["sharedReaderSHA256"] == PARENT_SHA, "basic source pin mismatch")


class Contracts(unittest.TestCase):
    def test_only_observed_modern_lowercase_single_words(self):
        bands = dict.fromkeys(["я", "ещё", "Москва", "из-за", "два слова", "мір", "a", "я1"], 0)
        self.assertTrue(eligible("я", bands)); self.assertTrue(eligible("ещё", bands))
        for word in ["Москва", "из-за", "два слова", "мір", "a", "я1", "е\u0308ще", "наблюдение"]:
            self.assertFalse(eligible(word, bands))

    def test_bounds_are_not_silently_relaxed(self):
        self.assertFalse(eligible("", {"": 0}))
        self.assertTrue(eligible("я" * 12, {"я" * 12: 0}))
        self.assertFalse(eligible("я" * 13, {"я" * 13: 0}))

    def test_mutable_or_absent_manifest_cannot_supply_pins(self):
        with self.assertRaises(ValueError): verify_pins({})
        with self.assertRaises(ValueError): verify_pins({str(SWIFT): "0" * 64})


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dictionary", type=Path); p.add_argument("--frequency-wheel", type=Path)
    p.add_argument("--output-root", type=Path, default=Path(__file__).resolve().parents[1])
    for flag in ["self-test", "check-bundled", "check"]: p.add_argument("--" + flag, action="store_true")
    args = p.parse_args()
    if args.self_test:
        return 0 if unittest.TextTestRunner().run(unittest.defaultTestLoader.loadTestsFromTestCase(Contracts)).wasSuccessful() else 1
    if args.check_bundled:
        verify_bundled(args.output_root); print("Russian basic bundled integrity passed"); return 0
    require(args.dictionary is not None and args.frequency_wheel is not None, "both pinned snapshots required")
    outputs = artifacts(parent_module(Path(__file__).resolve().parents[1]), args.dictionary, args.frequency_wheel)
    verify_pins({str(path): sha(data) for path, data in outputs.items() if path != MANIFEST})
    require(sha(outputs[MANIFEST]) == MANIFEST_SHA, "source manifest reproduction mismatch")
    for path, data in outputs.items():
        target = args.output_root / path
        if args.check: require(target.read_bytes() == data, "source reproduction mismatch: " + str(path))
        else:
            require(not target.exists(), "refusing to overwrite: " + str(path))
            target.parent.mkdir(parents=True, exist_ok=True); target.write_bytes(data)
    print("Russian basic source reproduction checked" if args.check else "Russian basic corpus prepared")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
