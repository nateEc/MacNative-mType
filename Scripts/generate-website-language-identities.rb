#!/usr/bin/env ruby
# frozen_string_literal: true

# Mechanical identifier metadata only: never reads reference dictionaries,
# code, font files, palettes or other assets into the application.
require "json"

root = File.expand_path("..", __dir__)
fixture = JSON.parse(File.read(File.join(root, "Compatibility/official-languages.json")))
abort "unexpected reference version" unless fixture.fetch("referenceCommit") == "91bd24bb8513785c7364cbea29296ff7adafac41"
names = fixture.fetch("officialIDs")
mapping = fixture.fetch("nativeIndependent")
abort "language identity coverage drift" unless names.length == 446 && names.uniq == names && mapping.keys.sort == names.sort
abort "language identity is not bijective" unless mapping.values.uniq.length == names.length
abort "unsupported identity spelling" unless mapping.all? { |name, target| name.match?(/\A[A-Za-z0-9_+]+\z/) && target.match?(/\A[A-Za-z][A-Za-z0-9_]*\z/) }

output = +<<~SWIFT
  // Generated by Scripts/generate-website-language-identities.rb from the
  // project's audited identity metadata. Contains no reference word data.
  enum WebsiteLanguageIdentity {
    static let byWebsiteName: [String: TypingLanguage] = [
SWIFT
names.each { |name| output << "    #{name.inspect}: .#{mapping.fetch(name)},\n" }
output << <<~SWIFT
    ]

    private static let byNativeLanguage = Dictionary(uniqueKeysWithValues:
      byWebsiteName.map { ($0.value, $0.key) })

    static func language(for name: String) -> TypingLanguage? {
      guard name.utf8.allSatisfy({ $0 < 128 }) else { return nil }
      return byWebsiteName[name]
    }

    static func name(for language: TypingLanguage) -> String? {
      byNativeLanguage[language]
    }
  }
SWIFT
target = File.join(root, "Sources/Typebar/WebsiteLanguageIdentity.swift")
if ARGV == ["--check"]
  abort "generated website language identities drift" unless File.file?(target) && File.read(target) == output
  puts "website language identity generation check passed (#{names.length} mappings)"
elsif ARGV.empty?
  File.write(target, output)
else
  abort "usage: #{$PROGRAM_NAME} [--check]"
end
