#!/usr/bin/env python3
"""Reproduce basic Bokmål/Nynorsk from separate pinned Ordbank/unigram inputs."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import unittest

PARENT_SHA = "0df8e1a39edb41f69ca82278660409846494ac4cf1543da2007403b5afee1082"
REVISION = "ordbank-20220201-nb-unigrams-basic-v1"
ALPHABET = frozenset("abcdefghijklmnopqrstuvwxyzæøå")
SPECS = {"nob": (200, 1, 9, 1, 9), "nno": (250, 1, 10, 1, 10)}
LEGACY = {
    "nob": "morgen vindu papir kyst vind øvelse oppmerksomhet rolig klar sjø gate bord lys reise tålmodighet øyeblikk by regn stillhet retning stjerne notat hage åndedrag liten tid vær fjær".split(),
    "nno": "morgon vindauge papir strand vind øving merksemd roleg klår vatn gate bord lys reise tolmod stund by regn stille retning stjerne notat hage andning liten tid vår øy ven ikkje kvar noko".split(),
}
SWIFT = Path("Sources/Typebar/NorwegianBasicCorpus.generated.swift")
NOTICES = Path("Resources/NorwegianBasicCorpusNotices.txt")
SOURCES = Path("Resources/NorwegianBasicCorpusSources.txt")
MANIFEST = Path("Compatibility/norwegian-basic-corpus.json")
PUBLISHED = {
    str(SWIFT): "65fa72315466d52b2f8fe2e38913f8cc90b7153323702f99c371eb2cc719dbd3",
    str(NOTICES): "76ff513a994df50d6ec757f201ade440675279570b9f2c36db17489e84829489",
    str(SOURCES): "1cc2314b9f241acba2b077dbdc4604a03c837c3bd26a2725ec522bf11ae5fcdf",
}
MANIFEST_SHA = "7979abbcfdca66cc3351e28a4681ea5af4e81e4b5afa533b747608a2efe1e6aa"


def require(value, message):
    if not value:
        raise ValueError(message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def parent_module(root):
    path = root / "Scripts/prepare-norwegian-corpus.py"
    require(sha(path.read_bytes()) == PARENT_SHA, "shared Ordbank reader pin mismatch")
    spec = importlib.util.spec_from_file_location("norsk_literal_reader", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def eligible(word, maximum, counts):
    return type(word) is str and 1 <= len(word) <= maximum and set(word) <= ALPHABET and counts.get(word, 0) > 0


def native(pools):
    result = ("// Generated by Scripts/prepare-norwegian-basic-corpus.py; do not edit.\n"
              "// Separate Norsk ordbank/unigram selections; CC BY 4.0 dictionary, CC0 counts.\n"
              "enum NorwegianBasicCorpus {\n" + f'  static let revision = "{REVISION}"\n')
    for language, words in pools.items():
        result += f'  static let {language}: [String] = """\n' + "\n".join(words) + '\n""".split(separator: "\\n").map(String.init)\n'
    return (result + "}\n").encode()


def artifacts(parent, paths):
    pools, details = {}, {}
    mapping = ("# language\tword\tlemmaID\tfullformRowID\tcasefoldWholeTokenCount\n"
               "# Source: pinned Norsk ordbank LOEPENR/LEMMA_ID and each standard's own unigram list.\n"
               "# Counts aggregate case variants; no component estimates substitute for whole forms.\n")
    for language, spec in SPECS.items():
        forms, rows = parent.read_dictionary(paths[language][0], language)
        counts, frequency = parent.read_frequency(paths[language][1], language, forms)
        candidates = [w for w in forms if eligible(w, spec[2], counts)]
        retained = [w for w in LEGACY[language] if w in candidates]
        excluded = {w: "length" if len(w) > spec[2] else "no_whole_count" if counts[w] == 0 else "not_normative_literal"
                    for w in LEGACY[language] if w not in retained}
        required = list(dict.fromkeys(parent.RESERVED[language] + retained))
        words, capacity = parent.select_group(candidates, spec, counts, required)
        parent.validate(words, {"L": spec})
        require(all(counts[w] > 0 for w in words), "unobserved basic form")
        pools[language] = words
        details[language] = {"dictionaryRows": rows, "frequency": frequency,
            "eligibleCandidates": capacity, "retainedAuthored": retained,
            "authoredOutsideFreshPool": excluded, "shape": parent.shape(words),
            "wordsSHA256": sha(("\n".join(words) + "\n").encode())}
        for word in words:
            mapping += "\t".join([language, word, *(str(n) for n in forms[word]), str(counts[word])]) + "\n"
    notice = ("Typebar independent basic Norwegian corpora\nRevision: " + REVISION + "\n\n"
              "Norsk ordbank: Nasjonalbiblioteket / Språkbanken; Språkrådet and Universitetet i Bergen.\n"
              "Adapted selection under Creative Commons Attribution 4.0 International (CC BY 4.0).\n"
              "https://creativecommons.org/licenses/by/4.0/\n"
              "N-gram unigrams: Nasjonalbiblioteket / Språkbanken, CC0 1.0.\n"
              "https://creativecommons.org/publicdomain/zero/1.0/\n\n"
              "Changes: choose 200 Bokmål and 250 Nynorsk literal normert dictionary forms\n"
              "with TILDATO=4000, modern lowercase letters, lengths 1–9 and 1–10.\n"
              "Use each standard's own positive whole-token unigram counts; aggregate\n"
              "original case variants, never borrow counts from the other standard or\n"
              "component estimates. Keep eligible earlier authored words and real length\n"
              "boundaries. Two earlier Bokmål words exceed the new basic length bound;\n"
              "one earlier Nynorsk word has no whole-form observation in its snapshot.\n"
              "Their saved historical prompts, metrics and replay remain literal.\n"
              "These fixed 2022 dictionaries are not the live normative database;\n"
              "historical observations do not establish current frequency or lexical quality.\n"
              "No reference words, recasing, suffix synthesis, spelling normalization or\n"
              "padding. Matching candidate counts and bounds is not word-value, frequency,\n"
              "difficulty or semantic equivalence. The ten scale corpora retain their own\n"
              "revision and bytes. Raw dictionaries, frequency lists and media not bundled.\n\n")
    for language, source in parent.INPUTS.items():
        notice += language + " (snapshots retrieved 2026-10-29):\n"
        for key, value in source.items(): notice += key + ": " + value + "\n"
        notice += "\n"
    notice = notice.rstrip() + "\n"
    outputs = {SWIFT: native(pools), NOTICES: notice.encode(), SOURCES: mapping.encode()}
    document = {"schemaVersion": 1, "revision": REVISION, "sharedReaderSHA256": PARENT_SHA,
        "sourceInputs": parent.INPUTS, "wholeTokenObservationsRequired": True,
        "referenceAggregate": {k: list(v) for k, v in SPECS.items()}, "pools": details,
        "runtimeDependencies": [], "filesSHA256": {str(p): sha(v) for p, v in outputs.items()}}
    outputs[MANIFEST] = (json.dumps(document, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()
    return outputs


def verify_pins(hashes):
    require(bool(PUBLISHED) and hashes == PUBLISHED, "immutable basic corpus pins required")


def verify_bundled(root):
    parent = parent_module(root)
    require(bool(MANIFEST_SHA) and sha((root / MANIFEST).read_bytes()) == MANIFEST_SHA, "basic manifest immutable pin mismatch")
    document = json.loads((root / MANIFEST).read_text())
    require(document["revision"] == REVISION and document["schemaVersion"] == 1, "unsupported basic corpus manifest")
    verify_pins(document["filesSHA256"])
    for path, expected in PUBLISHED.items(): require(sha((root / path).read_bytes()) == expected, "bundled basic file mismatch: " + path)
    text = (root / SWIFT).read_text()
    matches = re.findall(r'  static let (nob|nno): \[String\] = """\n(.*?)\n"""', text, re.S)
    pools = {k: body.splitlines() for k, body in matches}
    require(len(matches) == len(pools) == 2 and list(pools) == list(SPECS) and native(pools) == text.encode(), "native basic template mismatch")
    rows = [row.split("\t") for row in (root / SOURCES).read_text().splitlines() if not row.startswith("#")]
    require(len(rows) == 450 and all(len(r) == 5 and all(v.isdigit() for v in r[2:]) and int(r[4]) > 0 for r in rows), "invalid basic row provenance")
    for language, words in pools.items():
        parent.validate(words, {"L": SPECS[language]})
        require(all(set(w) <= ALPHABET for w in words), "invalid basic alphabet")
        require([r[1] for r in rows if r[0] == language] == words, "basic row coverage mismatch")
        require(document["pools"][language]["shape"] == parent.shape(words)
                and document["pools"][language]["wordsSHA256"] == sha(("\n".join(words) + "\n").encode()), "basic content metadata mismatch")


class Contracts(unittest.TestCase):
    def test_observed_lowercase_single_words_only(self):
        counts = dict.fromkeys(["å", "øving", "Øving", "to ord", "a-b", "1", "nord", "e\u0301", "øvinger"], 1)
        self.assertTrue(eligible("å", 9, counts)); self.assertTrue(eligible("øving", 10, counts))
        for word in ["Øving", "to ord", "a-b", "1", "e\u0301", "ukjend"]:
            self.assertFalse(eligible(word, 9, counts))
        self.assertFalse(eligible("nord", 9, {"nord": 0}))

    def test_each_standard_keeps_its_length_bound(self):
        self.assertTrue(eligible("a" * 9, 9, {"a" * 9: 1}))
        self.assertFalse(eligible("a" * 10, 9, {"a" * 10: 1}))
        self.assertTrue(eligible("a" * 10, 10, {"a" * 10: 1}))

    def test_missing_or_manifest_supplied_pins_rejected(self):
        with self.assertRaises(ValueError): verify_pins({})
        with self.assertRaises(ValueError): verify_pins({str(SWIFT): "0" * 64})


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for language in SPECS:
        p.add_argument("--" + language + "-dictionary", type=Path)
        p.add_argument("--" + language + "-frequency", type=Path)
    p.add_argument("--output-root", type=Path, default=Path(__file__).resolve().parents[1])
    for flag in ["self-test", "check-bundled", "check"]: p.add_argument("--" + flag, action="store_true")
    args = p.parse_args()
    if args.self_test:
        return 0 if unittest.TextTestRunner().run(unittest.defaultTestLoader.loadTestsFromTestCase(Contracts)).wasSuccessful() else 1
    if args.check_bundled:
        verify_bundled(args.output_root); print("Norwegian basic bundled integrity passed"); return 0
    paths = {k: (getattr(args, k + "_dictionary"), getattr(args, k + "_frequency")) for k in SPECS}
    require(all(all(v) for v in paths.values()), "four pinned snapshots required")
    outputs = artifacts(parent_module(Path(__file__).resolve().parents[1]), paths)
    verify_pins({str(p): sha(v) for p, v in outputs.items() if p != MANIFEST})
    require(sha(outputs[MANIFEST]) == MANIFEST_SHA, "source manifest reproduction mismatch")
    if not args.check: require(not any((args.output_root / p).exists() for p in outputs), "refusing to overwrite basic artifacts")
    for path, data in outputs.items():
        target = args.output_root / path
        if args.check: require(target.read_bytes() == data, "source reproduction mismatch: " + str(path))
        else:
            target.parent.mkdir(parents=True, exist_ok=True); target.write_bytes(data)
    print("Norwegian basic source reproduction checked" if args.check else "Norwegian basic corpora prepared")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
