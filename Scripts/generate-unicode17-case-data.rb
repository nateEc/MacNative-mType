#!/usr/bin/env ruby
# Standard Unicode data, not reference-project code or assets. See the bundled
# Unicode notice. Inputs are the exact public UCD 17.0.0 files named below.
require 'digest'

directory, mode = ARGV
abort 'usage: generate-unicode17-case-data.rb UCD_DIRECTORY --stdout|--check' unless directory && %w[--stdout --check].include?(mode)
hashes = {
  'UnicodeData.txt' => '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
  'SpecialCasing.txt' => 'efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588',
  'DerivedCoreProperties.txt' => '24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08'
}
data = hashes.to_h do |name, digest|
  text = File.binread(File.join(directory, name))
  abort "wrong UCD input: #{name}" unless Digest::SHA256.hexdigest(text) == digest
  [name, text.force_encoding('UTF-8')]
end
upper, lower = {}, {}
data['UnicodeData.txt'].each_line do |line|
  fields = line.strip.split(';', -1)
  code = fields[0].to_i(16)
  upper[code] = [fields[12].to_i(16)] unless fields[12].empty?
  lower[code] = [fields[13].to_i(16)] unless fields[13].empty?
end
conditions = []
data['SpecialCasing.txt'].each_line do |line|
  record = line.split('#', 2).first.strip
  next if record.empty?
  code, down, _title, up, condition = record.split(';').map(&:strip)
  if condition.nil? || condition.empty?
    upper[code.to_i(16)] = up.split.map { |value| value.to_i(16) }
    lower[code.to_i(16)] = down.split.map { |value| value.to_i(16) }
  elsif condition.split.none? { |value| %w[lt tr az].include?(value) }
    conditions << [code, down, condition]
  end
end
abort 'unsupported root case condition' unless conditions == [['03A3', '03C2', 'Final_Sigma']]
properties = {'Cased' => [], 'Case_Ignorable' => []}
data['DerivedCoreProperties.txt'].each_line do |line|
  record = line.split('#', 2).first.strip
  next if record.empty?
  span, property = record.split(';').map(&:strip)
  next unless properties.key?(property)
  bounds = span.split('..').map { |value| value.to_i(16) }
  properties[property] << [bounds.first, bounds.last]
end
hex = -> value { value.to_s(16).upcase }
mapping = -> map { map.sort.reject { |code, value| value == [code] }.map { |code, value|
  "#{hex.call(code)}:#{value.map(&hex).join('.')}"
}.join(';') }
ranges = -> property { properties.fetch(property).sort.map { |first, last| "#{hex.call(first)}-#{hex.call(last)}" }.join(';') }
output = <<~SWIFT
  // Generated by Scripts/generate-unicode17-case-data.rb from public UCD 17.0.0.
  // Unicode data copyright © 2025 Unicode, Inc.; see Resources/UnicodeNotice.txt.
  // No reference-project source or assets. Input hashes are pinned in the generator.
  enum WebsiteUnicode17CaseData {
    static let upper = mappings("#{mapping.call(upper)}")
    static let lower = mappings("#{mapping.call(lower)}")
    static let cased = ranges("#{ranges.call('Cased')}")
    static let ignorable = ranges("#{ranges.call('Case_Ignorable')}")

    private static func mappings(_ text: String) -> [UInt32: [UInt32]] {
      Dictionary(uniqueKeysWithValues: text.split(separator: ";").map { record in
        let parts = record.split(separator: ":", omittingEmptySubsequences: false)
        return (UInt32(parts[0], radix: 16)!, parts[1].split(separator: ".").map { UInt32($0, radix: 16)! })
      })
    }

    private static func ranges(_ text: String) -> [ClosedRange<UInt32>] {
      text.split(separator: ";").map { record in
        let bounds = record.split(separator: "-")
        return UInt32(bounds[0], radix: 16)!...UInt32(bounds[1], radix: 16)!
      }
    }
  }
SWIFT
target = File.expand_path('../Sources/Typebar/WebsiteUnicode17CaseData.swift', __dir__)
if mode == '--stdout'
  print output
else
  abort 'Unicode case data differs from pinned generator output' unless File.binread(target) == output.b
  puts 'Unicode 17 generated case data check passed'
end
