#!/usr/bin/env python3
"""Build-time only: independently sourced English words, never reference data.

Requires msgpack==1.1.2 in an isolated preparation environment. Does not install
packages, download inputs, or execute wordfreq. The native app needs no Python.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import zipfile

SCOWL_COMMIT = "7e99edab8e32f9f9ea2b15f249ca8d4d67237410"
WHEEL_SHA256 = "4b1c6ecffc6198be3396d5cf871c4423ca71c907c231348d352dd54d62b97473"
CHOICE_COUNTS = (1000, 5000, 9944, 24141)
WORD_COUNT = CHOICE_COUNTS[-1]
REVISION = "scowl-2026.02.25-wordfreq-3.1.1-v2"
SWIFT_PATH = Path("Sources/Typebar/EnglishFrequencyCorpus.generated.swift")
PROVENANCE_PATH = Path("Compatibility/english-frequency-corpus.json")
NOTICES_PATH = Path("Resources/EnglishFrequencyCorpusNotices.txt")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def select_words(dictionary, bins, count):
    """Dictionary membership, descending frequency bands, deterministic case.

    Keep dictionary spellings, preferring a lowercase form, then title case,
    then lexical order. I is kept as the English pronoun. Do not invent forms
    or pad a short corpus. Punctuation/digit/accent practice remains separate.
    """
    if type(count) is not int or count < 1:
        raise ValueError("word count must be positive")
    forms = {}
    for word in sorted(set(dictionary)):
        if re.fullmatch(r"[A-Za-z]+", word):
            forms.setdefault(word.lower(), []).append(word)
    canonical = {
        token: min(words, key=lambda word: (word != token, word != token.title(), word))
        for token, words in forms.items()
    }
    if "I" in forms.get("i", []):
        canonical["i"] = "I"
    result, bands, seen = [], [], set()
    if not isinstance(bins, list):
        raise ValueError("frequency bins must be an array")
    for band, tokens in enumerate(bins):
        if not isinstance(tokens, list) or any(type(token) is not str for token in tokens):
            raise ValueError("frequency band must contain strings")
        if tokens != sorted(tokens) or len(tokens) != len(set(tokens)):
            raise ValueError("frequency band is not sorted and unique")
        for token in tokens:
            if token in seen:
                raise ValueError("frequency token appears in multiple bands")
            seen.add(token)
            if token in canonical:
                result.append(canonical[token])
                bands.append(band)
    if len(result) < count:
        raise ValueError(f"insufficient real dictionary words: {len(result)} < {count}")
    return result[:count], bands[:count], len(result)


def read_frequency(wheel):
    raw = wheel.read_bytes()
    if digest(raw) != WHEEL_SHA256:
        raise ValueError("wordfreq 3.1.1 wheel SHA-256 mismatch")
    import msgpack
    if msgpack.__version__ != "1.1.2":
        raise ValueError("preparation requires msgpack==1.1.2")
    with zipfile.ZipFile(wheel) as archive:
        packed = archive.read("wordfreq/data/large_en.msgpack.gz")
        decoded = msgpack.unpackb(gzip.decompress(packed), raw=False)
        if not isinstance(decoded, list) or not decoded or decoded[0] != {"format": "cB", "version": 1}:
            raise ValueError("unexpected wordfreq frequency format")
        metadata = archive.read("wordfreq-3.1.1.dist-info/METADATA").decode("utf-8")
        notices = metadata[metadata.index("## License"):].strip() + "\n"
    return decoded[1:], packed, notices


def scowl_words(root):
    def run(*command):
        return subprocess.check_output(command, cwd=root, text=True, stderr=subprocess.PIPE)
    if run("git", "rev-parse", "HEAD").strip() != SCOWL_COMMIT:
        raise ValueError("SCOWL checkout must be pinned to rel-2026.02.25")
    if run("git", "status", "--porcelain", "--untracked-files=normal").strip():
        raise ValueError("SCOWL source checkout must be clean")
    # Never trust a cached database. Build from pinned source into a fresh path.
    with tempfile.TemporaryDirectory(prefix="typebar-scowl-build-") as temporary:
        database = str(Path(temporary) / "scowl.db")
        subprocess.run([sys.executable, "combine.py", "create-db", database],
                       cwd=root, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        words = run(sys.executable, "scowl", "--db", database,
                    "word-list", "60", "A", "1", "--categories=")
    return words.splitlines(), (root / "Copyright").read_text(encoding="utf-8")


def artifacts(words, bands, candidate_count, packed, scowl_notice, wordfreq_notice):
    text = "\n".join(words) + "\n"
    swift = (
        "// Generated by Scripts/prepare-english-frequency-corpus.py; do not edit.\n"
        "// Independent SCOWL / wordfreq data, adapted by Typebar contributors.\n"
        "// Word selection data: CC BY-SA 4.0; full attribution and source notices:\n"
        "// Resources/EnglishFrequencyCorpusNotices.txt. No Monkeytype data.\n"
        "enum EnglishFrequencyCorpus {\n"
        f'  static let revision = "{REVISION}"\n'
        '  static let words: [String] = """\n' + text +
        '""".split(separator: "\\n").map(String.init)\n}\n'
    )
    notice = (
        "Typebar English frequency corpus, revision 2\n"
        "Adapted selection by Typebar contributors (2026). The selected word data\n"
        "is distributed under CC BY-SA 4.0: https://creativecommons.org/licenses/by-sa/4.0/\n"
        "Changes: intersect English frequency tokens with SCOWL size 60, American\n"
        "spelling, variant level 1, default category; restrict to ASCII letters;\n"
        "prefer existing lowercase/title spellings, preserve I, retain the first\n"
        "24,141 frequency-ranked entries. No reference-project words are imported.\n\n"
        "SCOWL rel-2026.02.25\n"
        f"https://github.com/en-wl/wordlist/tree/{SCOWL_COMMIT}\n\n" + scowl_notice +
        "\nwordfreq 3.1.1 — Robyn Speer and contributors\n"
        "https://pypi.org/project/wordfreq/3.1.1/\n"
        "The data license is CC BY-SA 4.0, not the Apache license for its code.\n"
        "The following release metadata retains source credits and SUBTLEX terms.\n\n" + wordfreq_notice
    )
    provenance = {
        "schemaVersion": 1,
        "revision": REVISION,
        "scowl": {"commit": SCOWL_COMMIT, "size": 60, "spelling": "A",
                  "variantLevel": 1, "categories": [""], "copyrightSHA256": digest(scowl_notice.encode())},
        "wordfreq": {"version": "3.1.1", "wheelSHA256": WHEEL_SHA256,
                     "member": "wordfreq/data/large_en.msgpack.gz", "memberSHA256": digest(packed)},
        "preparationDependency": "msgpack==1.1.2 (build-time only)",
        "selection": "ASCII dictionary forms, frequency bands descending, lowercase/title/lexical case preference; preserve I",
        "candidateCount": candidate_count,
        "count": len(words), "uniqueCount": len(set(words)),
        "wordsSHA256": digest(text.encode()), "swiftSHA256": digest(swift.encode()),
        "noticesSHA256": digest(notice.encode()),
        "choices": {str(n): {"count": n, "lastFrequencyBand": bands[n - 1],
                            "wordsSHA256": digest(("\n".join(words[:n]) + "\n").encode()),
                            "minimumLength": min(map(len, words[:n])),
                            "maximumLength": max(map(len, words[:n]))}
                    for n in CHOICE_COUNTS},
        "dataLicense": "CC-BY-SA-4.0; retain SCOWL and wordfreq source notices",
    }
    return {SWIFT_PATH: swift.encode(), NOTICES_PATH: notice.encode(),
            PROVENANCE_PATH: (json.dumps(provenance, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode()}


def publish(outputs, root, check):
    if check:
        for relative, data in outputs.items():
            if not (root / relative).is_file() or (root / relative).read_bytes() != data:
                raise ValueError(f"generated artifact mismatch: {relative}")
    else:
        # Validate the entire destination set before creating anything.
        if any((root / relative).exists() for relative in outputs):
            raise ValueError("refusing to replace existing artifacts; use a new output root or --check")
        for relative, data in outputs.items():
            target = root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)


def verify_bundled(root):
    """Offline integrity check; upstream reproduction is the stronger check."""
    provenance = json.loads((root / PROVENANCE_PATH).read_text(encoding="utf-8"))
    swift = (root / SWIFT_PATH).read_bytes()
    notice = (root / NOTICES_PATH).read_bytes()
    if provenance["swiftSHA256"] != digest(swift) or provenance["noticesSHA256"] != digest(notice):
        raise ValueError("bundled corpus or notices hash mismatch")
    match = re.search(rb'  static let words: \[String\] = """\n([A-Za-z\n]+)"""\.split', swift)
    if not match:
        raise ValueError("invalid native word data section")
    body = match.group(1)
    words = body.decode("ascii").splitlines()
    if (len(words) != WORD_COUNT or len(set(words)) != WORD_COUNT
            or any(not re.fullmatch(r"[A-Za-z]+", word) for word in words)
            or body != ("\n".join(words) + "\n").encode()
            or provenance["wordsSHA256"] != digest(body)):
        raise ValueError("bundled corpus word contract mismatch")
    if (provenance["schemaVersion"] != 1 or provenance["revision"] != REVISION or provenance["count"] != WORD_COUNT
            or provenance["uniqueCount"] != WORD_COUNT
            or provenance["scowl"]["commit"] != SCOWL_COMMIT
            or provenance["wordfreq"]["wheelSHA256"] != WHEEL_SHA256):
        raise ValueError("bundled corpus provenance contract mismatch")
    for count in CHOICE_COUNTS:
        choice = provenance["choices"][str(count)]
        if (choice["count"] != count or choice["minimumLength"] != min(map(len, words[:count]))
                or choice["maximumLength"] != max(map(len, words[:count]))
                or choice["wordsSHA256"] != digest(("\n".join(words[:count]) + "\n").encode())):
            raise ValueError("bundled corpus choice metadata mismatch")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scowl-root", type=Path)
    parser.add_argument("--wordfreq-wheel", type=Path)
    parser.add_argument("--output-root", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--check-bundled", action="store_true")
    args = parser.parse_args()
    if args.check_bundled:
        if args.scowl_root or args.wordfreq_wheel or args.check:
            parser.error("--check-bundled does not take source inputs or --check")
        verify_bundled(args.output_root.resolve())
        print("Bundled English corpus integrity verified (not an upstream reproduction)")
        return
    if not args.scowl_root or not args.wordfreq_wheel:
        parser.error("source reproduction requires --scowl-root and --wordfreq-wheel")
    bins, packed, frequency_notice = read_frequency(args.wordfreq_wheel.resolve())
    dictionary, scowl_notice = scowl_words(args.scowl_root.resolve())
    words, bands, candidates = select_words(dictionary, bins, WORD_COUNT)
    publish(artifacts(words, bands, candidates, packed, scowl_notice, frequency_notice),
            args.output_root.resolve(), args.check)
    print(f"English corpus {'verified' if args.check else 'prepared'}: {len(words)} real dictionary entries; {candidates} ranked candidates")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
